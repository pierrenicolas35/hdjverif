-- =====================================================================
-- HDJ Vérif — thésaurus des synonymes de la recherche
--
-- OBJET
--   Une recherche par mots-clés ne trouve rien quand l'usager écrit autre chose que
--   le libellé officiel : « scanner » pour une « scanographie », « IRM » pour une
--   « remnographie », « anti-TNF » pour de l'« infliximab ». Ce fichier installe le
--   **thésaurus** qui élargit la requête, et rebranche dessus les deux recherches de
--   l'application (`rechercher_ccam`, `rechercher_medicaments`).
--
-- SOURCE DE VÉRITÉ
--   `data/thesaurus-synonymes.csv`, chargé par `scripts/import-referentiels.mjs`.
--   Le fichier est **la** référence : le SQL ne fait que le rejouer et l'interroger.
--   Les correspondances ne sont donc pas écrites ici (à une exception près, les mots
--   vides, qui doivent rester alignés sur `MOTS_VIDES` de `scripts/lib/thesaurus.mjs`).
--
-- MODÈLE
--   notion   : concept pivot (« tomodensitométrie ») ; ses termes sont synonymes
--   terme    : mot ou expression tel qu'on l'écrit (affiché à l'usager)
--   terme_normalise : clé de comparaison (minuscules, sans accent), calculée à l'import
--   domaine  : actes | medicaments | commun
--
-- À APPLIQUER APRÈS `rpc-recherche.sql` ET `ccam-arbres.sql` :
--   il REDÉFINIT `rechercher_ccam` et `rechercher_medicaments` pour y brancher le
--   thésaurus (les deux précédents fichiers restent la description du modèle).
--     psql < supabase/thesaurus.sql
--     node scripts/appliquer-sql.mjs supabase/thesaurus.sql --verifier
-- =====================================================================

create extension if not exists unaccent;
create extension if not exists pg_trgm;

-- ---------------------------------------------------------------------
-- 1. Normalisation (partagée par le thésaurus et les requêtes)
-- ---------------------------------------------------------------------

-- Doit rester **identique** à `normaliserTerme()` de `scripts/lib/thesaurus.mjs` :
-- minuscules, ligatures dépliées, accents retirés, tout séparateur ramené à une espace.
-- (STABLE, et non IMMUTABLE : `unaccent()` l'est lui-même. Aucun index ne s'appuie donc
--  sur cette fonction — les colonnes normalisées sont calculées à l'import.)
create or replace function public.normaliser_terme(p_texte text)
returns text
language sql
stable
set search_path = public, extensions, pg_catalog
as $$
  select nullif(
    btrim(
      regexp_replace(
        lower(unaccent(replace(replace(coalesce(p_texte, ''), 'œ', 'oe'), 'æ', 'ae'))),
        '[^a-z0-9]+', ' ', 'g'
      )
    ),
    ''
  );
$$;

comment on function public.normaliser_terme(text) is
  'Forme normalisée d''un terme de recherche : minuscules, sans accent ni ligature, séparateurs ramenés à une espace. Alignée sur normaliserTerme() du thésaurus.';

-- ---------------------------------------------------------------------
-- 2. Table du thésaurus
-- ---------------------------------------------------------------------
create table if not exists public.thesaurus_synonymes (
  id              bigint generated by default as identity primary key,
  notion          text not null,
  terme           text not null,
  terme_normalise text not null,
  type            text,
  domaine         text not null default 'commun'
                  check (domaine in ('actes', 'medicaments', 'commun')),
  source          text,
  unique (notion, terme_normalise)
);

comment on table public.thesaurus_synonymes is
  'Thésaurus des synonymes de la recherche (source : data/thesaurus-synonymes.csv). Deux termes de la même notion sont synonymes : chercher l''un trouve l''autre.';
comment on column public.thesaurus_synonymes.notion is
  'Concept pivot, en clair — jamais affiché : il ne sert qu''à rapprocher les termes.';
comment on column public.thesaurus_synonymes.terme_normalise is
  'Clé de comparaison (minuscules, sans accent), calculée à l''import — voir normaliser_terme().';
comment on column public.thesaurus_synonymes.domaine is
  'actes (nomenclature CCAM), medicaments (BDPM) ou commun.';

create index if not exists idx_thesaurus_terme
  on public.thesaurus_synonymes (terme_normalise);

create index if not exists idx_thesaurus_notion
  on public.thesaurus_synonymes (notion);

